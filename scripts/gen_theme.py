# ----------------------------------------------------------- xfwm4 PNG images
def gen_xfwm_pngs(t):
    """Generate complete set of 100% opaque PNG pixmaps for xfwm4 window frame & buttons."""
    p, g = t["palette"], t["gradients"]
    os.makedirs(XFWM_DIR, exist_ok=True)

    # All alphas must be 255 for full opacity and flawless window dragging in xfwm4
    top_c = hex_to_rgb(g["frame"]["from"]["hex"]) + (255,)
    bot_c = hex_to_rgb(g["frame"]["to"]["hex"]) + (255,)
    edge_c = hex_to_rgb(p["edge"]) + (255,)

    top_c_inact = tuple(int(c * 0.8) for c in top_c[:3]) + (255,)
    bot_c_inact = tuple(int(c * 0.8) for c in bot_c[:3]) + (255,)
    edge_c_inact = tuple(int(c * 0.7) for c in edge_c[:3]) + (255,)

    # 1. Titlebar vertical gradient strip (1x32 px)
    def make_title_strip(width, height, top, bot, edge):
        pixels = []
        for y in range(height):
            fac = y / float(height - 1) if height > 1 else 0
            c = (
                int(top[0] + (bot[0] - top[0]) * fac),
                int(top[1] + (bot[1] - top[1]) * fac),
                int(top[2] + (bot[2] - top[2]) * fac),
                255,
            )
            if y == 0:
                c = edge
            for _ in range(width):
                pixels.append(c)
        return pixels

    t_act = make_title_strip(1, 32, top_c, bot_c, edge_c)
    t_inact = make_title_strip(1, 32, top_c_inact, bot_c_inact, edge_c_inact)

    for i in range(1, 6):
        write_png(os.path.join(XFWM_DIR, f"title-{i}-active.png"), 1, 32, t_act)
        write_png(os.path.join(XFWM_DIR, f"title-{i}-inactive.png"), 1, 32, t_inact)

    # 2. Top-left & top-right corners (7x32 px)
    def make_top_corner(left_side, width, height, top, bot, edge):
        pixels = []
        border_x = 0 if left_side else (width - 1)
        for y in range(height):
            fac = y / float(height - 1) if height > 1 else 0
            base = (
                int(top[0] + (bot[0] - top[0]) * fac),
                int(top[1] + (bot[1] - top[1]) * fac),
                int(top[2] + (bot[2] - top[2]) * fac),
                255,
            )
            for x in range(width):
                if y == 0 or x == border_x:
                    pixels.append(edge)
                else:
                    pixels.append(base)
        return pixels

    write_png(
        os.path.join(XFWM_DIR, "top-left-active.png"),
        7,
        32,
        make_top_corner(True, 7, 32, top_c, bot_c, edge_c),
    )
    write_png(
        os.path.join(XFWM_DIR, "top-left-inactive.png"),
        7,
        32,
        make_top_corner(True, 7, 32, top_c_inact, bot_c_inact, edge_c_inact),
    )
    write_png(
        os.path.join(XFWM_DIR, "top-right-active.png"),
        7,
        32,
        make_top_corner(False, 7, 32, top_c, bot_c, edge_c),
    )
    write_png(
        os.path.join(XFWM_DIR, "top-right-inactive.png"),
        7,
        32,
        make_top_corner(False, 7, 32, top_c_inact, bot_c_inact, edge_c_inact),
    )

    # 3. Side borders (left, right: 7x1 px)
    def make_side(left_side, width, height, col, edge):
        pixels = []
        border_x = 0 if left_side else (width - 1)
        for _ in range(height):
            for x in range(width):
                pixels.append(edge if x == border_x else col)
        return pixels

    write_png(os.path.join(XFWM_DIR, "left-active.png"), 7, 1, make_side(True, 7, 1, bot_c, edge_c))
    write_png(
        os.path.join(XFWM_DIR, "left-inactive.png"),
        7,
        1,
        make_side(True, 7, 1, bot_c_inact, edge_c_inact),
    )
    write_png(
        os.path.join(XFWM_DIR, "right-active.png"), 7, 1, make_side(False, 7, 1, bot_c, edge_c)
    )
    write_png(
        os.path.join(XFWM_DIR, "right-inactive.png"),
        7,
        1,
        make_side(False, 7, 1, bot_c_inact, edge_c_inact),
    )

    # 4. Bottom border (1x7 px)
    def make_bottom(width, height, col, edge):
        pixels = []
        for y in range(height):
            c = edge if y == (height - 1) else col
            for _ in range(width):
                pixels.append(c)
        return pixels

