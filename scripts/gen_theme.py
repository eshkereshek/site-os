def hex_to_rgb(h):
    h = h.lstrip("#")
    if len(h) == 3:
        h = "".join(c * 2 for c in h)
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def rgb_to_hex(rgb):
    return "#{:02X}{:02X}{:02X}".format(*(int(round(max(0, min(255, v)))) for v in rgb[:3]))


def brighten(h, factor):
    return rgb_to_hex(tuple(c * factor for c in hex_to_rgb(h)))


def mix(a, b, t):
    ra, ga, ba = hex_to_rgb(a)
    rb, gb, bb = hex_to_rgb(b)
    return rgb_to_hex((ra + (rb - ra) * t, ga + (gb - ga) * t, ba + (bb - ba) * t))


def stop(v):
    if isinstance(v, str):
        return v
    if "alpha" in v and v["alpha"] < 1:
        return css_rgba(v["hex"], v["alpha"])
    return v["hex"]


def css_rgba(hexv, alpha):
    r, g, b = hex_to_rgb(hexv)
    return f"rgba({r},{g},{b},{alpha})"


def css_gradient(g):
    deg = 180 if g.get("dir") == "vertical" else 90
    return f"linear-gradient({deg}deg, {stop(g['from'])}, {stop(g['to'])})"


def avg_hex(g):
    f = g["from"] if isinstance(g["from"], str) else g["from"]["hex"]
    t = g["to"] if isinstance(g["to"], str) else g["to"]["hex"]
    rf, gf, bf = hex_to_rgb(f)
    rt, gt, bt = hex_to_rgb(t)
    return rgb_to_hex(((rf + rt) / 2, (gf + gt) / 2, (bf + bt) / 2))


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"[gen_theme] wrote {os.path.relpath(path, REPO)}")


def write_png(filepath, width, height, rgba_pixels):
    """Write an RGBA PNG without requiring external dependencies."""
    raw = bytearray()
    for y in range(height):
        raw.append(0)  # filter type 0 (None)
        row_start = y * width
        for x in range(width):
            raw.extend(rgba_pixels[row_start + x])
    compressed = zlib.compress(bytes(raw), 9)

    def chunk(tag, data):
        return (
            struct.pack(">I", len(data))
            + tag
            + data
            + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)
        )

    png = (
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0))
        + chunk(b"IDAT", compressed)
        + chunk(b"IEND", b"")
    )
    with open(filepath, "wb") as f:
        f.write(png)


