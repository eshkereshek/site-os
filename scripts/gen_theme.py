    # 6. Buttons: hide, close, and maximize.
    # Background must match titlebar vertical gradient so no transparent hole exists.
    def make_dot_button(color_hex, top, bot, edge):
        width, height = 22, 32
        cx, cy, r = 10.5, 15.5, 7.5
        dot_rgb = hex_to_rgb(color_hex)
        pixels = []
        for y in range(height):
            fac = y / float(height - 1)
            bg = (
                edge
                if y == 0
                else (
                    int(top[0] + (bot[0] - top[0]) * fac),
                    int(top[1] + (bot[1] - top[1]) * fac),
                    int(top[2] + (bot[2] - top[2]) * fac),
                    255,
                )
            )
            for x in range(width):
                dist = math.hypot(x - cx, y - cy)
                if dist <= r - 0.5:
                    pixels.append((dot_rgb[0], dot_rgb[1], dot_rgb[2], 255))
                elif dist <= r + 0.5:
                    a = r + 0.5 - dist
                    blended = (
                        int(dot_rgb[0] * a + bg[0] * (1.0 - a)),
                        int(dot_rgb[1] * a + bg[1] * (1.0 - a)),
                        int(dot_rgb[2] * a + bg[2] * (1.0 - a)),
                        255,
                    )
                    pixels.append(blended)
                else:
                    pixels.append(bg)
        return pixels

