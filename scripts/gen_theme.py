def hex_to_rgb(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def rgb_to_hex(rgb):
    return "#%02X%02X%02X" % tuple(max(0, min(255, round(c))) for c in rgb)


def brighten(h, factor):
    """Mockup hover uses filter: brightness(1.3)."""
    return rgb_to_hex([c * factor for c in hex_to_rgb(h)])


def mix(a, b, t):
    ra, rb = hex_to_rgb(a), hex_to_rgb(b)
    return rgb_to_hex([ra[i] + (rb[i] - ra[i]) * t for i in range(3)])


def stop(v):
    """Gradient stop: plain hex or {hex, alpha}. Returns (hex, alpha)."""
    if isinstance(v, dict):
        return v["hex"], v.get("alpha", 1.0)
    return v, 1.0


def css_rgba(hexv, alpha):
    r, g, b = hex_to_rgb(hexv)
    return f"rgba({r},{g},{b},{alpha:g})"


def css_gradient(g):
    a, aa = stop(g["from"])
    b, ba = stop(g["to"])
    if g["dir"] == "vertical":
        return f"linear-gradient(180deg, {css_rgba(a, aa)}, {css_rgba(b, ba)})"
    return f"linear-gradient(90deg, {css_rgba(a, aa)}, {css_rgba(b, ba)})"


def avg_hex(g):
    """Mid colour for renderers without gradients (jgmenu). Recorded in SPEC.md."""
    a, _ = stop(g["from"])
    b, _ = stop(g["to"])
    return mix(a, b, 0.5)


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"[gen_theme] wrote {os.path.relpath(path, REPO)}")


