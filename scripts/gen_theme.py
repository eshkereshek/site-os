# --------------------------------------------------------------- SPEC note
def note_spec(t):
    g = t["gradients"]
    text = f"""
## gen_theme.py: значения, которые не являются прямым переносом

- jgmenu не умеет градиенты. Фон меню: средний цвет `gradients.menu` = `{avg_hex(g['menu'])}`.
- ANSI-палитра терминала выведена, в макете есть только фон и текст.
- Hover кнопок окна: `brightness(1.3)` из макета, применён к `btn` и `btnClose`.
- Все значения помечены "не проверено в VM".
"""
    # Idempotent: replace the auto-generated block only.
    marker = "## gen_theme.py:"
    try:
        with open(SPEC, encoding="utf-8") as f:
            body = f.read()
    except FileNotFoundError:
        return
    if marker in body:
        body = body[:body.index(marker)].rstrip() + "\n"
    with open(SPEC, "w", encoding="utf-8", newline="\n") as f:
        f.write(body + text)
    print("[gen_theme] updated theme/SPEC.md (generated notes block)")


def main():
    t = load()
    write(os.path.join(THEME, "gtk-3.0", "gtk.css"), gen_gtk(t))
    write(os.path.join(THEME, "xfwm4", "themerc"), gen_themerc(t))
    gen_xpm(t)
    gen_jgmenu(t)
    gen_terminal(t)
    note_spec(t)


if __name__ == "__main__":
    main()
