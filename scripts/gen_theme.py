color_menu_fg = {p['dark']}
color_sel_bg = {mid_hover}
color_sel_fg = {p['dark']}
color_norm_bg = {mid_item}
color_norm_fg = {p['dark']}
color_border = {p['menuBorder']}
menu_width = {s['menuWidth']}
