# --------------------------------------------------------------- XPM buttons
def _xpm(name, fill, ring, mark, size=15):
    """Round button with a centred mark. Palette: . none, f fill, r ring, m mark."""
    cx = cy = (size - 1) / 2
    rows = []
    for y in range(size):
        row = []
        for xx in range(size):
            d = ((xx - cx) ** 2 + (y - cy) ** 2) ** 0.5
            if d > size / 2:
                row.append(".")
            elif d > size / 2 - 1.3:
                row.append("r")
            elif mark(xx, y, size):
                row.append("m")
            else:
                row.append("f")
        rows.append("".join(row))
    pal = [(".", "None"), ("f", fill), ("r", ring), ("m", "#1E2228")]
    lines = ["/* XPM */", f"static char * {name}_xpm[] = {{",
             f'"{size} {size} {len(pal)} 1",']
    lines += [f'"{k} c {v}",' for k, v in pal]
    lines += [f'"{r}",' for r in rows]
    lines[-1] = lines[-1].rstrip(",")
    lines.append("};")
    return "\n".join(lines) + "\n"


def mark_hide(x, y, n):
    c = (n - 1) // 2
    return y == c + 2 and c - 3 <= x <= c + 3


def mark_close(x, y, n):
    c = n - 1
    return (abs(x - y) <= 1 or abs(x + y - c) <= 1) and 3 <= x <= c - 3


def gen_xpm(t):
    p = t["palette"]
    ring = mix(p["edge"], p["bgEdge"], 0.2)
    specs = {
        "minimize": (p["btn"], mark_hide),
        "close": (p["btnClose"], mark_close),
    }
    for name, (fill, mark) in specs.items():
        write(os.path.join(XPM_DIR, f"{name}.xpm"), _xpm(name, fill, ring, mark))
        write(os.path.join(XPM_DIR, f"{name}-hover.xpm"),
              _xpm(name, brighten(fill, t["effects"]["hoverBrightness"]), ring, mark))


# --------------------------------------------------------------- jgmenu
